"""Настройки платформы, которые удобно менять руками."""

import os

# Что показывать по скрытым тестам ПОСЛЕ «Проверить» (до проверки их данные наружу не отдаются никогда):
#   "always" — всё: ввод, ожидаемый и полученный вывод, ошибки (учебный режим, по умолчанию)
#   "failed" — только у упавших скрытых тестов, у пройденных — лишь статус
#   "never"  — только статус
# Переопределение: переменная окружения HIDDEN_TESTS_REVEAL.
HIDDEN_TESTS_REVEAL = os.environ.get("HIDDEN_TESTS_REVEAL", "always").strip().lower()
if HIDDEN_TESTS_REVEAL not in ("always", "failed", "never"):
    HIDDEN_TESTS_REVEAL = "always"

# Таймаут одного теста при «Проверить», секунды
TEST_TIMEOUT = 3.0

# Сколько символов stderr / вывода отдавать в результатах тестов
MAX_STDERR = 2000
MAX_ACTUAL = 20000

# Сколько тестов запускать одновременно
TEST_PARALLEL = 4
